const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({window:{},esc:s=>String(s??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;'),skillLabel:s=>String(s.name||'#'+s.code).replaceAll('<','&lt;').replaceAll('>','&gt;'),iconUrl:s=>s.icon||null,color:()=> '#5bd5de',num:n=>String(n)});
vm.runInContext(fs.readFileSync('web/combat-insights.js','utf8'),context);
const run=s=>vm.runInContext(s,context),plain=x=>JSON.parse(JSON.stringify(x));
context.events=[{kind:'position',actor:1,at_ms:1000,position:[0,0]},{kind:'position',actor:1,at_ms:2000,position:[100,50]},{kind:'position',actor:2,at_ms:1500,position:[900,900]}];
assert.deepEqual(plain(run('replayPoints(events,500,[1])')),[],'no lookahead before first position');
assert.deepEqual(plain(run('replayPoints(events,1500,[1])[0].position')),[50,25]);
assert.equal(run('replayPoints(events,1500,[1])[0].interpolated'),true);
assert.equal(run('replayPoints(events,6000,[1]).length'),0,'stale positions disappear');
context.events[1].at_ms=10000;
assert.deepEqual(plain(run('replayPoints(events,2000,[1])[0].position')),[0,0],'no interpolation over a large missing interval');
assert.equal(run('contrastRatio([0,0,0],[255,255,255])'),21);
assert.equal(run('contrastRatio([50,50,50],[50,50,50])'),1);
assert.ok(run('overlayContrast({theme:"midnight",opacity:0,high_contrast:true})')>7);
assert.ok(run('overlayContrast({theme:"midnight",opacity:0})')<1.5);
context.f={target_id:50,boss_name:'Boss',duration_ms:10000,players:[{actor_id:1,name:'<script>bad</script>'}],analytics:{evidence:{events:[{kind:'hit',actor:1,target:50,at_ms:1000,skill:11,amount:100}],rotations:[]}}};
assert.match(run('rotationRows(f,1)'),/Keine Skill-Nutzungen/);
assert.doesNotMatch(run('rotationTimeline(f,1,0,10000)'),/<script>/);
context.f.analytics.evidence.rotations=[{actor:1,skill:11,name:'Skill',uses:1,per_minute:6,first_ms:1000,mean_gap_ms:null}];
assert.match(run('rotationRows(f,1)'),/6.0/);
assert.doesNotMatch(run('rotationRows(f,1)'),/<script>/);
assert.match(run('bossEvidence(f)'),/Keine Todesereignisse/);
console.log('PASS combat insights: 14 regression checks (sparse positions, truthful rotation, contrast, escaping)');
