// Numerical/presentation invariants independent of a browser executable.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../web/enhancements.js'),'utf8');
const context=vm.createContext({num:String,dur:String,esc:s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))});
vm.runInContext(source.slice(source.indexOf('function damageSamples('),source.indexOf('function hitTimeline(')),context);
const run=expression=>vm.runInContext(expression,context),plain=value=>JSON.parse(JSON.stringify(value));
context.f={players:[{actor_id:1,name:'One'}],analytics:{points:[{ms:500,damage:{1:1000,2:500}},{ms:1000,damage:{1:3000,2:1000}}]}};
const before=JSON.stringify(context.f);
assert.deepEqual(plain(run('damageSamples(f).map(p=>p.dps)')),[3000,5000]);
assert.deepEqual(plain(run('damageSamples(f,1).map(p=>p.dps)')),[2000,4000]);
assert.deepEqual(plain(run('damageSamples(f,null,5000).map(p=>p.dps)')),[3000,4000]);
assert.deepEqual(plain(run('damageSamples(f,1,5000).map(p=>p.total)')),[1000,3000]);
context.f.analytics.points=Array.from({length:14},(_,i)=>({ms:(i+1)*500,damage:{1:(i+1)*500+(i>=12?500:0)}}));
assert.equal(run('damageSamples(f,1,5000).at(-1).dps'),1100);
context.f.analytics.partial=true;context.f.analytics.points=[{ms:10000,damage:{1:1000000}},{ms:10500,damage:{1:1000100}},{ms:11000,damage:{1:1000200}}];
assert.deepEqual(plain(run('damageSamples(f,1,5000).map(p=>p.dps)')),[200,200]);
assert.deepEqual(plain(run('damageSamples(f,1).map(p=>p.dps)')),[200,200]);
assert.equal(run('damageSamples({})').length,0);
const singleton=run('curveMarkup([{ms:500,total:50}],[{name:"<script>",color:"var(--accent)",value:p=>p.total}],{width:280})');
assert.ok(singleton.includes('<circle'));assert.ok(!singleton.includes('<script>'));assert.ok(!singleton.includes('NaN'));
context.points=Array.from({length:100000},(_,i)=>({ms:i*500,v:i}));
const markup=run('curveMarkup(points,[{name:"Large",color:"var(--accent)",value:p=>p.v}])');
const path=markup.match(/<path d="([^"]+)"/)[1];assert.ok((path.match(/[ML]/g)||[]).length<=601);assert.match(markup,/99999\/s/);
assert.equal(run('damageSamples(f,1,5000); JSON.stringify(f)'),JSON.stringify(context.f),'rendering leaves stored samples intact');
context.original=JSON.parse(before);assert.equal(run('damageSamples(original,1,5000); JSON.stringify(original)'),before);
console.log('PASS chart samples, actor totals, rolling window, trimmed baseline, empty/single samples, escaping, downsampling and immutable records (8 chart checks)');
